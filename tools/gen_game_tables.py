"""Writes build/plugin-gen/gametables.h: what kind each monster and object row is, for the
game-state API (src/plugin/gameapi.h).

Reads monstats.txt and objects.txt from vanilla/ (your own game copy) and writes plain row lists,
so the plugin can tell an enemy from a town NPC, a mercenary or a summon, and a shrine from a
chest or a waypoint. tools/build-plugin.cmd runs it before every build; the output is in build/,
never committed (it comes from Blizzard's tables).
"""
import csv
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
EXCEL = ROOT / "vanilla" / "data" / "global" / "excel"
OUT = ROOT / "build" / "plugin-gen" / "gametables.h"

# Small animals the game marks as friendly (Align 1) or neutral (Align 2).
CRITTERS = {"rat", "bird1", "bird2", "bat", "maggot", "bug", "scorpion", "snake", "parrot", "fish", "seagull"}
# Friendly people who are not marked npc (town guards, the Act V barbarians).
ALLIES = {"act2guard3", "act5barb1", "act5barb2", "act5barb3", "act5barb4", "act5pow"}


def read(name):
    with open(EXCEL / name, encoding="latin1", newline="") as f:
        rows = list(csv.reader(f, delimiter="\t"))
    head = {k: i for i, k in enumerate(rows[0])}
    return head, rows[1:]


def monsters():
    h, rows = read("monstats.txt")
    out = {}
    for r in rows:
        get = lambda k: r[h[k]] if h[k] < len(r) else ""
        if not get("*hcIdx").strip().isdigit():
            continue
        row, name, align = int(get("*hcIdx")), get("Id"), get("Align")
        if get("npc") == "1" or name in ALLIES:
            kind = "Npc"
        elif "hire" in name.lower():
            kind = "Mercenary"
        elif name in CRITTERS or align == "2":
            kind = "Critter"
        elif align == "1":
            kind = "Summon"
        else:
            kind = "Enemy"
        out[row] = (kind, name)
    return out


def bosses():
    """Rows marked boss in monstats.txt (act bosses, Blood Raven, Griswold, the Summoner...)."""
    h, rows = read("monstats.txt")
    out = []
    for r in rows:
        get = lambda k: r[h[k]] if h[k] < len(r) else ""
        if get("*hcIdx").strip().isdigit() and get("boss") == "1":
            out.append(int(get("*hcIdx")))
    return sorted(out)


def objects():
    h, rows = read("objects.txt")
    out = {}
    for r in rows:
        get = lambda k: r[h[k]] if h[k] < len(r) else ""
        if not get("*ID").strip().isdigit():
            continue
        row, sub = int(get("*ID")), int(get("SubClass") or 0)
        name = get("Name")
        if row == 267:
            kind = "Stash"
        elif row == 39:
            kind = "Fire"
        elif sub & 64:
            kind = "Waypoint"
        elif sub & 4 or sub & 16:
            kind = "Portal"
        elif sub & 1:
            kind = "Shrine"
        elif sub & 32:
            kind = "Well"
        elif get("IsDoor") == "1" or sub & 128:
            kind = "Door"
        elif sub & 8:
            kind = "Chest"
        else:
            kind = "Other"
        out[row] = (kind, name)
    return out


def table(name, enum, rows):
    size = max(rows) + 1
    lines = [f"inline constexpr {enum} {name}[{size}] = {{"]
    for row in range(size):
        kind, _ = rows.get(row, ("Enemy" if enum == "MonsterClass" else "Other", ""))
        lines.append(f"\t{enum}::{kind},  // {row}")
    lines.append("};")
    return "\n".join(lines)


def main():
    text = f"""// GENERATED by tools/gen_game_tables.py from monstats.txt and objects.txt. Do not edit by hand.
// What kind each monster and object row is (gameapi.h). Rows past the end (the mod's own new
// rows) count as enemies and "other" objects.
#pragma once

#include <cstdint>

namespace Game {{

enum class MonsterClass : uint8_t {{ Enemy, Npc, Mercenary, Summon, Critter }};
enum class ObjectKind : uint8_t {{ Other, Shrine, Chest, Waypoint, Portal, Door, Well, Stash, Fire }};

namespace Tables {{

{table("MonsterClasses", "MonsterClass", monsters())}

{table("ObjectKinds", "ObjectKind", objects())}

// monstats.txt rows marked boss, sorted.
inline constexpr uint16_t BossRows[] = {{ {", ".join(str(b) for b in bosses())} }};

}}  // namespace Tables
}}  // namespace Game
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:  # unchanged: no rebuild
        OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
